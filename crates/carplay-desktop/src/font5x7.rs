//! Lightweight 5x7 ASCII bitmap font & 2D rounded-rect renderer for HUD overlays and test frames.

pub fn fill_rect(
    fb: &mut [u32],
    fb_w: usize,
    fb_h: usize,
    x: usize,
    y: usize,
    w: usize,
    h: usize,
    color: u32,
) {
    let x_end = (x + w).min(fb_w);
    let y_end = (y + h).min(fb_h);
    for py in y.min(fb_h)..y_end {
        let row = &mut fb[py * fb_w..];
        for px in x.min(fb_w)..x_end {
            row[px] = color;
        }
    }
}

pub fn fill_circle(
    fb: &mut [u32],
    fb_w: usize,
    fb_h: usize,
    cx: i32,
    cy: i32,
    radius: i32,
    color: u32,
) {
    let r2 = radius * radius;
    for dy in -radius..=radius {
        let py = cy + dy;
        if py < 0 || py >= fb_h as i32 {
            continue;
        }
        for dx in -radius..=radius {
            let px = cx + dx;
            if px < 0 || px >= fb_w as i32 {
                continue;
            }
            if dx * dx + dy * dy <= r2 {
                fb[(py as usize) * fb_w + (px as usize)] = color;
            }
        }
    }
}

pub fn draw_text(
    fb: &mut [u32],
    fb_w: usize,
    fb_h: usize,
    mut x: usize,
    y: usize,
    scale: usize,
    color: u32,
    text: &str,
) {
    let s = scale.max(1);
    for ch in text.chars() {
        let glyph = glyph_5x7(ch);
        for (col_idx, &col_bits) in glyph.iter().enumerate() {
            for row_idx in 0..7usize {
                if ((col_bits >> row_idx) & 1) != 0 {
                    fill_rect(
                        fb,
                        fb_w,
                        fb_h,
                        x + col_idx * s,
                        y + row_idx * s,
                        s,
                        s,
                        color,
                    );
                }
            }
        }
        x += 6 * s;
        if x >= fb_w {
            break;
        }
    }
}

